export function findAbilityByNameOrId(identifier: string): ClassAbilityDetail | undefined {
  if (!identifier) return undefined;
  const lower = identifier.toLowerCase().trim();
  return CLASS_ABILITIES_CATALOG.find(ab => 
    ab.id.toLowerCase() === lower || ab.name.toLowerCase() === lower
  );
}
